function detectLang(): "en" | "it" {
	const raw = (process.env.INGOMBRO_LANG || process.env.LC_ALL || process.env.LC_MESSAGES || process.env.LANG || "").toLowerCase();
	return raw.startsWith("it") ? "it" : "en";
}

export const lang = detectLang();
export const T: Dict = lang === "it" ? it : en;

export function fmt(s: string, vars: Record<string, string | number>): string {
	return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
